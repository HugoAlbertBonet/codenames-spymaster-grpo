"""Build a reproducible, common-word vocabulary for Codenames training.

Run with the build-only dependency installed on demand:

    uv run --with wordfreq python scripts/build_training_vocabulary.py

The output is frequency ordered. Board generation samples uniformly from the
file, so this ordering is mainly useful for reviewing and reproducing it.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path
import re
import sys

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from codenames_env import DEFAULT_VOCABULARY


# Function words make poor Codenames tiles and can dominate a frequency list.
# This is deliberately small and transparent; the source still supplies the
# semantic vocabulary and frequency ordering.
STOPWORDS = frozenset(
    "a an and are as at be been but by can could did do does for from had has "
    "have he her hers him his how i if in into is it its just me more my no "
    "not of on one or our ours she should so some than that the their theirs "
    "them then there these they this to too up us was we were what when where "
    "which who will with would you your yours"
    .split()
)
WORD_RE = re.compile(r"^[a-z]+$")


def _frequency_words(source_json: Path | None, count: int) -> list[str]:
    if source_json is not None:
        rows = json.loads(source_json.read_text(encoding="utf-8"))
        return [str(row[0]) for row in rows]
    try:
        from wordfreq import top_n_list
    except ImportError as exc:
        raise SystemExit(
            "This generator needs wordfreq, or --source-json with a wordfreq JSON dump. "
            "Run it with: uv run --with wordfreq python scripts/build_training_vocabulary.py"
        ) from exc
    return top_n_list("en", count)


def build_vocabulary(
    target_size: int,
    min_length: int,
    max_length: int,
    excluded_files: list[Path] | None = None,
    source_json: Path | None = None,
) -> list[str]:

    excluded = {word.strip().lower() for word in DEFAULT_VOCABULARY}
    for path in excluded_files or []:
        for raw_line in path.read_text(encoding="utf-8").splitlines():
            word = raw_line.split("#", 1)[0].strip().lower()
            if word:
                excluded.add(word)
    selected: list[str] = []
    seen = set(excluded)
    # Request more candidates than the target because punctuation, inflected
    # forms, stopwords, and short tokens are removed below.
    for raw_word in _frequency_words(source_json, max(target_size * 12, 20_000)):
        word = raw_word.strip().lower()
        if (
            word in seen
            or word in STOPWORDS
            or not WORD_RE.fullmatch(word)
            or not min_length <= len(word) <= max_length
        ):
            continue
        selected.append(word)
        seen.add(word)
        if len(selected) + len(DEFAULT_VOCABULARY) >= target_size:
            break

    vocabulary = list(DEFAULT_VOCABULARY) + selected
    if len(vocabulary) < target_size:
        raise RuntimeError(
            f"Only found {len(vocabulary)} usable words; lower --target-size or widen the filters"
        )
    return vocabulary[:target_size]


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=Path("data/training_vocabulary.txt"))
    parser.add_argument("--target-size", type=int, default=5_000)
    parser.add_argument("--min-length", type=int, default=3)
    parser.add_argument("--max-length", type=int, default=14)
    parser.add_argument(
        "--source-json",
        type=Path,
        help="Optional wordfreq-en-25000-log.json dump; avoids installing wordfreq during generation",
    )
    parser.add_argument(
        "--exclude-file",
        type=Path,
        action="append",
        default=[Path("data/evaluation_vocabulary_oov.txt")],
        help="Vocabulary file(s) whose words must not appear in training (repeatable)",
    )
    return parser.parse_args()


def main() -> None:
    args = parse_args()
    excluded_files = [path for path in args.exclude_file if path.exists()]
    vocabulary = build_vocabulary(
        args.target_size,
        args.min_length,
        args.max_length,
        excluded_files=excluded_files,
        source_json=args.source_json,
    )
    args.output.parent.mkdir(parents=True, exist_ok=True)
    metadata = (
        "# Generated by scripts/build_training_vocabulary.py\n"
        "# Source: wordfreq top_n_list('en', frequency-ranked common English words)\n"
        "# Source dump: https://github.com/aparrish/wordfreq-en-25000\n"
        "# The built-in 88-word vocabulary is retained; function words and non-ASCII/punctuated tokens are filtered.\n"
        f"# Excluded files: {', '.join(str(path) for path in excluded_files) or 'none'}\n"
        f"# Count: {len(vocabulary)}\n"
    )
    args.output.write_text(metadata + "\n".join(vocabulary) + "\n", encoding="utf-8")
    print(f"Wrote {len(vocabulary)} words to {args.output}")


if __name__ == "__main__":
    main()
